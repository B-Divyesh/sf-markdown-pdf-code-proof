import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(repository, 'site', 'src', 'demo-transcript.ts');
const temporaryRoot = mkdtempSync(join(tmpdir(), 'codeproof-transcript-'));
const workspace = join(temporaryRoot, 'workspace');

try {
  const result = spawnSync('cargo', [
    'run', '--quiet', '--locked', '--manifest-path', 'cli/Cargo.toml', '--',
    'demo', '--out', workspace
  ], { cwd: repository, encoding: 'utf8' });

  if (result.status !== 1) {
    throw new Error(`codeproof demo returned ${result.status}: ${result.stderr}`);
  }
  if (result.stderr) {
    throw new Error(`codeproof demo wrote unexpected stderr: ${result.stderr}`);
  }

  const normalized = result.stdout
    .trimEnd()
    .replaceAll(workspace, '/tmp/codeproof-demo-…');
  const lines = normalized.split('\n');
  const expected = [
    'DEMO HOLD — do not release — 1 expected defect found',
    '  Error [code.flow-changed] Code fence on line 7 is present but its line flow changed',
    'Sample workspace: /tmp/codeproof-demo-…',
    'HTML proof sheet: /tmp/codeproof-demo-…/proof/index.html'
  ];

  if (JSON.stringify(lines) !== JSON.stringify(expected)) {
    throw new Error(`The bundled demo transcript changed:\n${normalized}`);
  }

  const generated = `// Generated by scripts/generate-demo-transcript.mjs from the real CLI.\n` +
    `// Temporary paths are the only normalized values.\n` +
    `export const demoTranscript = ${JSON.stringify(lines, null, 2)} as const;\n`;

  if (process.argv.includes('--check')) {
    if (readFileSync(outputPath, 'utf8') !== generated) {
      throw new Error('site/src/demo-transcript.ts is stale; run npm run generate:demo-transcript');
    }
  } else {
    writeFileSync(outputPath, generated);
  }
} finally {
  rmSync(temporaryRoot, { recursive: true, force: true });
}
